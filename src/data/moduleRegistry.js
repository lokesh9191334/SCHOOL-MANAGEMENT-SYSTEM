const ALL_MODULES = [...MODULE_REGISTRY, ...ROLE_EXTRA_MODULES]

export function getModuleConfig(pathname) {
  const exact = ALL_MODULES.find((m) => m.path === pathname)
  const base = exact || ALL_MODULES.find((m) => pathname === m.path || pathname.startsWith(`${m.path}/`))
  if (!base) return null
  if (PRINT_PATHS.has(base.path) && !base.printEnabled) {
    return { ...base, printEnabled: true }
  }
  return base
}

export function getModulePaths() {
  return ALL_MODULES.map((m) => m.path)
}
