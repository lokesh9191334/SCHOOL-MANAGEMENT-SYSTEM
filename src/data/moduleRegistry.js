const col = (key, label) => ({ key, label })
const field = (key, label, type = 'text', extra = {}) => ({ key, label, type, ...extra })

function mod({
  path,
  section,
  title,
  description,
  idPrefix,
  storageKey,
  seed,
  columns,
  fields,
  statusOptions,
  statusKey = 'status',
  links = [],
  features = [],
  createLabel = 'Add record',
  recordActions = [],
  computeStats,
  searchPlaceholder,
  inviteRole,
  notifyParentsOnStatus,
  printEnabled,
}) {
  return {
    path,
    section,
    title,
    description,
    idPrefix,
    storageKey: storageKey || `sms_mod_${path.replace(/\W+/g, '_')}`,
    seed,
    columns,
    fields,
    statusOptions,
    statusKey,
    links,
    features,
    createLabel,
    recordActions,
    computeStats,
    searchPlaceholder: searchPlaceholder || `Search ${title.toLowerCase()}...`,
    inviteRole,
    notifyParentsOnStatus,
    printEnabled,
    parentScoped: path.startsWith('/parent/'),
  }
}

