const col = (key, label) => ({ key, label })
const field = (key, label, type = 'text', extra = {}) => ({ key, label, type, ...extra })

function mod(config) {
  const {
    path,
    section,
    title,
    description,
    idPrefix,
    storageKey,
    seed = [],
    columns = [],
    fields = [],
    statusOptions = ['Active', 'Pending'],
    statusKey = 'status',
    links = [],
    features = [],
    createLabel = 'Add record',
    recordActions = [],
    inviteRole,
    notifyParentsOnStatus,
    printEnabled,
  } = config
  return {
    path,
    section,
    title,
    description,
    idPrefix,
    storageKey: storageKey || `sms_mod_${path.replace(/\W+/g, '_')}`,
    seed,
    columns,
    fields,
    statusOptions,
    statusKey,
    links,
    features,
    createLabel,
    recordActions,
    searchPlaceholder: `Search ${title.toLowerCase()}...`,
    inviteRole,
    notifyParentsOnStatus,
    printEnabled,
    parentScoped: path.startsWith('/parent/'),
  }
}

